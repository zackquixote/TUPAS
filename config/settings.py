def _load_dotenv(path):
    """Populate os.environ from a simple KEY=VALUE file.

    Existing shell variables always win, so exporting a key in the terminal
    still overrides the .env file. This keeps the project runnable out of the
    box without pulling in python-dotenv.
    """
    try:
        lines = path.read_text(encoding='utf-8-sig').splitlines()
    except (FileNotFoundError, IsADirectoryError, UnicodeDecodeError, OSError):
        return

    for raw_line in lines:
        line = raw_line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, _, value = line.partition('=')
        key = key.strip()
        if key.startswith('export '):
            key = key[len('export '):].strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        if key:
            os.environ.setdefault(key, value)


_load_dotenv(BASE_DIR / '.env')


def _env_bool(name, default=False):
    """Read a boolean environment variable (0/false/no/off mean False)."""
    raw = os.environ.get(name)
    if raw is None or not raw.strip():
        return default
    return raw.strip().lower() not in {'0', 'false', 'no', 'off'}


